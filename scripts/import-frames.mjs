import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const targetDir = path.join(projectRoot, 'public', 'assets', 'frames');
const manifestFile = path.join(projectRoot, 'src', 'data', 'constructionFrames.js');

// Candidate desktop locations
const userProfile = process.env.USERPROFILE || 'C:\\Users\\nk183';
const candidateSources = [
  path.join(userProfile, 'Desktop', 'frames_realstate'),
  path.join(userProfile, 'OneDrive', 'Desktop', 'frames_realstate'),
  path.join('C:', 'Users', 'nk183', 'Desktop', 'frames_realstate')
];

let sourceDir = null;
for (const cand of candidateSources) {
  try {
    if (fs.existsSync(cand) && fs.statSync(cand).isDirectory()) {
      sourceDir = cand;
      break;
    }
  } catch (err) {
    // continue
  }
}

if (!sourceDir) {
  console.error('[IMPORT ERROR] Could not find frames_realstate on Desktop.');
  console.error('Searched candidates:', candidateSources);
  process.exit(1);
}

console.log(`[IMPORT] Found source directory at: ${sourceDir}`);

// Ensure target directories exist
fs.mkdirSync(targetDir, { recursive: true });
fs.mkdirSync(path.dirname(manifestFile), { recursive: true });

// Read files
const supportedExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif']);
const entries = fs.readdirSync(sourceDir);

const frameItems = [];

for (const entry of entries) {
  const ext = path.extname(entry).toLowerCase();
  if (!supportedExtensions.has(ext)) continue;

  const match = entry.match(/(\d+)/);
  if (!match) continue;

  const frameNum = parseInt(match[1], 10);
  frameItems.push({
    originalName: entry,
    frameNum,
    ext,
    sourcePath: path.join(sourceDir, entry)
  });
}

if (frameItems.length === 0) {
  console.error('[IMPORT ERROR] No supported image frames found in source directory.');
  process.exit(1);
}

// Sort numerically
frameItems.sort((a, b) => a.frameNum - b.frameNum);

console.log(`[IMPORT] Located ${frameItems.length} sequential frame items.`);
console.log(`[IMPORT] Range: frame ${frameItems[0].frameNum} to frame ${frameItems[frameItems.length - 1].frameNum}`);

// Copy and standardize filenames: frame-001.jpg (preserves pristine visual quality)
const manifestUrls = [];
let missingFrames = 0;

for (let i = 0; i < frameItems.length; i++) {
  const item = frameItems[i];
  const padIndex = String(i + 1).padStart(3, '0');
  const targetFileName = `frame-${padIndex}${item.ext}`;
  const targetFilePath = path.join(targetDir, targetFileName);

  // Copy without modifying original
  fs.copyFileSync(item.sourcePath, targetFilePath);
  manifestUrls.push(`/assets/frames/${targetFileName}`);
}

console.log(`[IMPORT] Successfully copied ${manifestUrls.length} frames to: ${targetDir}`);

// Generate manifest file
const manifestContent = `// Frame Manifest for Construction Scroll Animation
// Automatically generated by scripts/import-frames.mjs
// Total verified frames: ${manifestUrls.length}

export const TOTAL_CONSTRUCTION_FRAMES = ${manifestUrls.length};

export const CONSTRUCTION_FRAMES = Object.freeze([
${manifestUrls.map(url => `  ${JSON.stringify(url)}`).join(',\n')}
]);

export const FRAME_METADATA = {
  totalFrames: ${manifestUrls.length},
  firstFrame: ${JSON.stringify(manifestUrls[0])},
  lastFrame: ${JSON.stringify(manifestUrls[manifestUrls.length - 1])},
  isAvailable: ${manifestUrls.length > 0},
  source: 'Desktop/frames_realstate'
};

export default CONSTRUCTION_FRAMES;
`;

fs.writeFileSync(manifestFile, manifestContent, 'utf-8');
console.log(`[IMPORT] Generated manifest at: ${manifestFile}`);
